const dict = { de, en };
export type MsgKey = keyof typeof de;

export function translate(lang: Lang, key: MsgKey, vars: Record<string, string | number> = {}): string {
  return dict[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

/** Parts outside the catalogue (e.g. imported tube lengths) fall back to a generic label. */
export function partLabel(lang: Lang, key: string): string {
  if (key in dict[lang]) return dict[lang][key as MsgKey];
  const tube = /^tube-(\d+)$/.exec(key);
  if (tube) return `${lang === 'de' ? 'Rohr' : 'Tube'} ${Number(tube[1]) / 10} cm`;
  const panel = /^panel-(\d+)x(\d+)/.exec(key);
  if (panel) return `${lang === 'de' ? 'Platte' : 'Panel'} ${Number(panel[1]) / 10}×${Number(panel[2]) / 10} cm`;
  return key;
}
